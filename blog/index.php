    <script>
        document.addEventListener('DOMContentLoaded', function () {
            var filterBtns = document.querySelectorAll('#sl-blog-filters .sl-subnav__chip');
            var cards = document.querySelectorAll('.sl-blog-card');
            var searchInput = document.getElementById('sl-blog-search');
            var countLabel = document.getElementById('sl-blog-count');
            var emptyState = document.getElementById('sl-blog-empty');

            var currentCategory = 'all';
            var currentSearch = '';

            function updateCards() {
                var visibleCount = 0;

                cards.forEach(function (card) {
                    var category = card.getAttribute('data-category');
                    var title = card.querySelector('.sl-blog-card__title').textContent.toLowerCase();
                    var excerpt = card.querySelector('.sl-blog-card__excerpt').textContent.toLowerCase();
                    var keywords = (card.getAttribute('data-keywords') || '').toLowerCase();

                    var matchCategory = (currentCategory === 'all' || category === currentCategory);
                    var matchSearch = true;

                    if (currentSearch) {
                        var terms = currentSearch.split(' ');
                        matchSearch = terms.every(function (term) {
                            return title.indexOf(term) !== -1 || excerpt.indexOf(term) !== -1 || keywords.indexOf(term) !== -1;
                        });
                    }

                    if (matchCategory && matchSearch) {
                        card.style.display = 'flex';
                        visibleCount++;
                    } else {
                        card.style.display = 'none';
                    }
                });

                countLabel.textContent = 'Showing ' + visibleCount + ' article' + (visibleCount === 1 ? '' : 's');
                if (emptyState) {
                    emptyState.style.display = (visibleCount === 0) ? 'block' : 'none';
                }
            }

            filterBtns.forEach(function (btn) {
                btn.addEventListener('click', function () {
                    filterBtns.forEach(function (b) { b.classList.remove('is-active'); });
                    btn.classList.add('is-active');
                    currentCategory = btn.getAttribute('data-filter');
                    updateCards();
                });
            });

            if (searchInput) {
                searchInput.addEventListener('input', function () {
                    currentSearch = this.value.trim().toLowerCase();
                    updateCards();
                });
            }
        });
    </script>

