                            <tr>
                                <td><strong>Organization</strong></td>
                                <td>5 Modules (1: Admin, 2: Summaries, 3: Quality, 4: Non-clinical, 5: Clinical).</td>
                                <td>4 Parts (I: Administrative, II: Quality, III: Non-clinical, IV: Clinical).</td>
