                <h2 id="dossier-structures">1. Comparing CTD and ACTD Formats</h2>
                <p>Depending on the importing territory, health ministries require registration submissions structured under one of two standardized guidelines:</p>
                <div class="table-responsive">
                    <table class="table table-bordered table-striped" style="margin: 20px 0; font-size: 15px;">
                        <thead style="background: #020025; color: #ffffff;">
