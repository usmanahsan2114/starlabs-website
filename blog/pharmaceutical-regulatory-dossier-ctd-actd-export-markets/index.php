                <h2 id="quality-module">2. Module 3 / Part II: The Quality (CMC) Dossier</h2>
                <p>The core of any generic drug registration application is the Quality or Chemistry, Manufacturing, and Controls (CMC) section. Star Laboratories' regulatory affairs team compiles comprehensive technical data covering:</p>
                <ul class="sl-checklist">
                    <li><strong>Drug Substance (S Section):</strong> Nomenclature, structure, physicochemical characteristics, synthesis route summary, specification, analytical procedures, and retest period.</li>
                    <li><strong>Drug Product (P Section):</strong> Pharmaceutical development, formulation components, overages, manufacturing process flow charts, critical process controls (CPCs), and packaging barrier specifications.</li>
                    <li><strong>Analytical Method Validation:</strong> Full ICH Q2(R1) validation data confirming specificity, linearity, range, accuracy, precision, and robustness for chromatographic assays.</li>
                </ul>

                <h2 id="stability-zones">3. Stability Testing Protocols for Zone IVa &amp; IVb</h2>
                <p>Developing nations across Asia and Africa present high ambient heat and humidity requiring rigorous stability compliance:</p>
                <p>Drug dossiers must demonstrate real-time and accelerated stability stability in environmental test chambers adhering strictly to <strong>ICH Zone IVa ($30^\circ\text{C} \pm 2^\circ\text{C} / 65\% \pm 5\% \text{RH}$)</strong> or <strong>Zone IVb ($30^\circ\text{C} \pm 2^\circ\text{C} / 75\% \pm 5\% \text{RH}$)</strong>. At Star Laboratories, batches are tested at 0, 3, 6, 9, 12, 18, 24, and 36 months to validate shelf-life claims.</p>

                <h2 id="copp-who">4. WHO Certification Scheme &amp; The CoPP</h2>
                <p>The <strong>Certificate of Pharmaceutical Product (CoPP)</strong> is an indispensable requirement for international health ministry submissions. Issued by DRAP in accordance with WHO guidelines, it validates three essential facts:</p>
                <ol class="sl-steps">
                    <li><span>1</span><div><h3>Marketing Authorization Status</h3><p>Certifies that the specific drug formulation is actively registered and authorized for commercial distribution in Pakistan.</p></div></li>
                    <li><span>2</span><div><h3>Manufacturing Site cGMP Compliance</h3><p>Confirms that the manufacturing facility in Lahore undergoes routine statutory inspection and adheres to WHO-recommended Good Manufacturing Practices.</p></div></li>
                    <li><span>3</span><div><h3>Approved Labeling &amp; Packaging</h3><p>Accompanies approved packaging artwork, summary of product characteristics (SmPC), and active formulation breakdown.</p></div></li>
                </ol>

