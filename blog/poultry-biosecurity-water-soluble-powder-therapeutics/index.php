                <h2 id="poultry-diseases">1. Major Commercial Poultry Pathogens in Pakistan</h2>
                <p>Commercial poultry farms encounter a continuous barrage of bacterial, viral, and parasitic challenges:</p>
                <ul class="sl-checklist">
                    <li><strong>Mycoplasmosis &amp; Colibacillosis:</strong> <em>Mycoplasma gallisepticum</em> and avian pathogenic <em>Escherichia coli</em> (APEC) cause severe fibrinopurulent airsacculitis, perihepatitis, and pericarditis in broiler flocks.</li>
                    <li><strong>Coccidiosis:</strong> Protozoan parasites of the genus <em>Eimeria</em> (e.g. <em>E. tenella</em>, <em>E. necatrix</em>) destroy intestinal mucosal integrity, causing bloody diarrhea, poor FCR, and secondary necrotic enteritis (<em>Clostridium perfringens</em>).</li>
                    <li><strong>Environmental Heat Stress:</strong> Ambient temperatures exceeding 38&deg;C cause severe respiratory alkalosis, electrolyte imbalances, and immune suppression, sharply elevating flock mortality.</li>
                </ul>

