                <h2 id="bioavailability">1. Bioavailability &amp; Pharmacokinetic Profiles</h2>
                <p>The rate and extent of systemic drug absorption following oral administration depend fundamentally on the physical state in which the active pharmaceutical ingredient (API) reaches the gastrointestinal tract:</p>
                <p>For solid dosage forms (tablets, capsules), the absorption cascade requires three consecutive physiological steps: <strong>disintegration</strong> &rarr; <strong>deaggregation</strong> &rarr; <strong>dissolution</strong> in gastric or intestinal fluids. For poorly soluble compounds (Biopharmaceutics Classification System Class II and IV), dissolution is frequently the rate-limiting step governing oral bioavailability.</p>
                <p>Conversely, in oral solutions, the active molecule is already in molecular dispersion, bypassing disintegration and dissolution. Consequently, solutions typically exhibit faster onset of action ($T_{max}$) and higher initial peak plasma concentrations ($C_{max}$) compared to unformulated compressed tablets.</p>

