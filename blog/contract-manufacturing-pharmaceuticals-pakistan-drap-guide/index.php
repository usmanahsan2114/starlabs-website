                <h2 id="drap-framework">3. DRAP Regulatory Requirements &amp; Legal Compliance</h2>
                <p>Contract manufacturing in Pakistan is governed under the <strong>Drugs Act 1976</strong> and the <strong>DRAP Act 2012</strong>. Under these provisions, any outsourcing agreement must satisfy the following statutory checkpoints:</p>
                <ul class="sl-checklist">
                    <li><strong>Valid Drug Manufacturing Licence (DML):</strong> The contracted facility must possess a current, unencumbered DML covering the specific dosage section (e.g., Cephalosporin Injectable, General Oral Solids, Veterinary Suspensions).</li>
                    <li><strong>Formal Technical &amp; Quality Agreement:</strong> A comprehensive legal document defining batch release authority, Quality Assurance (QA) responsibilities, deviation reporting, stability monitoring, and product recall protocols.</li>
                    <li><strong>DRAP Notification / Prior Approval:</strong> In accordance with statutory rules, third-party manufacturing arrangements must be notified to and sanctioned by the Central Licensing Board (CLB) or relevant DRAP registration boards.</li>
                    <li><strong>Certificate of Pharmaceutical Product (CoPP):</strong> Essential for products intended for export, confirming compliance with WHO-recommended standards.</li>
                </ul>

