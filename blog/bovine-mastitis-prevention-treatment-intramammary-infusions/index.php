                <h2 id="detection">2. Early Detection: California Mastitis Test (CMT) &amp; SCC</h2>
                <p>Because subclinical mastitis produces no visible abnormalities in milk or quarter morphology, dairy operators must screen routinely using the <strong>California Mastitis Test (CMT)</strong>:</p>
                <p>The CMT reagent disrupts somatic cell membranes (primarily neutrophils infiltrating the mammary gland to fight infection), releasing cellular DNA that forms a viscous gel. Scoring from Negative (liquid) to Trace, 1, 2, and 3 (thick jelly-like mass) correlates directly with Somatic Cell Count (&gt;200,000 cells/ml indicates subclinical infection).</p>

                <h2 id="intramammary">3. Formulation Science of Intramammary Infusions</h2>
                <p>Intramammary infusions require sophisticated vehicle engineering to guarantee therapeutic drug concentrations throughout the glandular parenchymal tissue:</p>
                <ul class="sl-checklist">
                    <li><strong>Aseptic Syringe Filling:</strong> Infusions must be prepared under Class A laminar airflow in sterile pre-filled syringes with smooth, blunt cannulas that do not injure the teat sphincter keratin plug.</li>
                    <li><strong>Non-Irritating Lipid Vehicles:</strong> Formulated using pharmaceutical-grade mineral or vegetable oil matrices containing micronized broad-spectrum antimicrobials (penicillins, aminoglycosides, tetracyclines) that disperse uniformly in milk without causing mammary epithelial irritation.</li>
                    <li><strong>Dual Action (Lactating vs. Dry):</strong> Lactating formulations feature fast-release bases designed for rapid quarter clearance within 48 to 72 hours. Dry cow formulations utilize slow-release aluminum monostearate or sustained-release bases providing 4 to 6 weeks of active antibacterial protection.</li>
                </ul>

                <h2 id="dry-cow">4. Dry Cow Therapy (DCT) Protocols</h2>
                <p>The dry period (typically 60 days before the next expected calving) represents the most critical window to cure existing subclinical infections and protect the vulnerable involuting udder from new environmental invasions:</p>
                <ol class="sl-steps">
                    <li><span>1</span><div><h3>Preparation &amp; Aseptic Cleansing</h3><p>Completely milk out the udder. Thoroughly disinfect each teat apex using individual alcohol wipes, starting with the furthest teats first.</p></div></li>
                    <li><span>2</span><div><h3>Partial Insertion Infusion</h3><p>Infuse the long-acting dry cow intramammary tube using partial insertion (inserting only 2-3mm of the cannula tip into the teat orifice) to avoid disrupting the natural keratin barrier.</p></div></li>
                    <li><span>3</span><div><h3>Teat Dip Barrier Application</h3><p>Immediately dip all four teats in a high-viscosity, barrier-forming post-milking disinfectant (iodophor or chlorhexidine based).</p></div></li>
                </ol>

                <h2 id="prevention">5. Milking Hygiene &amp; 5-Point Management Program</h2>
                <p>Global dairy health authorities advocate the proven 5-point mastitis management plan:</p>
                <ul class="sl-checklist">
                    <li>Post-milking teat disinfection after every milking.</li>
                    <li>Prompt, clinically sound treatment of all clinical cases.</li>
                    <li>Universal Dry Cow Therapy (DCT) at the end of every lactation.</li>
                    <li>Culling of chronically infected cows refractory to repeated therapy.</li>
                    <li>Regular dynamic maintenance and testing of mechanical milking machines (pulsation rate, vacuum levels).</li>
                </ul>

